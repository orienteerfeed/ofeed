CREATE TABLE `UserNotification` (
  `id` VARCHAR(191) NOT NULL,
  `userId` INTEGER UNSIGNED NOT NULL,
  `eventId` VARCHAR(191) NOT NULL,
  `entryId` VARCHAR(191) NOT NULL,
  `kind` ENUM('ENTRY_ORDER_RECEIVED', 'ENTRY_PAYMENT_RECEIVED') NOT NULL,
  `sourceKey` VARCHAR(191) NOT NULL,
  `eventName` VARCHAR(255) NOT NULL,
  `itemCount` INTEGER UNSIGNED NULL,
  `amount` DECIMAL(10,2) NULL,
  `currency` CHAR(3) NULL,
  `method` VARCHAR(32) NULL,
  `createdAt` DATETIME(3) NOT NULL DEFAULT CURRENT_TIMESTAMP(3),
  `readAt` DATETIME(3) NULL,
  `publishedAt` DATETIME(3) NULL,
  PRIMARY KEY (`id`),
  UNIQUE INDEX `UserNotification_user_source_uq` (`userId`, `sourceKey`),
  INDEX `UserNotification_user_created_idx` (`userId`, `createdAt`, `id`),
  INDEX `UserNotification_unread_idx` (`userId`, `readAt`),
  INDEX `UserNotification_pending_idx` (`publishedAt`, `createdAt`),
  INDEX `UserNotification_created_idx` (`createdAt`),
  CONSTRAINT `UserNotification_userId_fkey` FOREIGN KEY (`userId`) REFERENCES `User` (`id`) ON DELETE CASCADE ON UPDATE CASCADE,
  CONSTRAINT `UserNotification_eventId_fkey` FOREIGN KEY (`eventId`) REFERENCES `Event` (`id`) ON DELETE CASCADE ON UPDATE CASCADE,
  CONSTRAINT `UserNotification_entryId_fkey` FOREIGN KEY (`entryId`) REFERENCES `Entry` (`id`) ON DELETE CASCADE ON UPDATE CASCADE
) DEFAULT CHARACTER SET utf8mb4 COLLATE utf8mb4_unicode_ci;
